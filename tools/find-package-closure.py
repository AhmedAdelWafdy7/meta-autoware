#!/usr/bin/env python3
"""List everything the seed packages depend on, transitively, and flag any
dependency that is excluded from scope. Use before adding a launch aggregator
to an image: its build-time dependencies count even if a launch argument
disables that subsystem at runtime.

Usage:
    tools/find-package-closure.py <seed-pn> [...] [--excluded results/<run>/skipped-packages.json]
"""
import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _recipe_graph import build_graph  # noqa: E402


def _latest_skipped_packages_json():
    """Newest results/universe-*/skipped-packages.json."""
    candidates = sorted(
        (REPO_ROOT / "results").glob("universe-*/skipped-packages.json"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    return str(candidates[0]) if candidates else None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("seeds", nargs="+", help="PN(s) to compute the forward closure of")
    parser.add_argument("--recipes-dir", default=str(REPO_ROOT / "meta-autoware" / "generated-recipes"))
    parser.add_argument(
        "--excluded",
        default=_latest_skipped_packages_json(),
        help="defaults to the most recently modified results/universe-*/skipped-packages.json",
    )
    args = parser.parse_args()

    recipes_dir = Path(args.recipes_dir)
    if not recipes_dir.is_dir():
        print(f"FAIL: {recipes_dir} not found", file=sys.stderr)
        sys.exit(1)

    graph = build_graph(recipes_dir)

    excluded_by_name = {}
    if not args.excluded:
        print(
            "WARNING: no results/universe-*/skipped-packages.json found -- "
            "closure will be checked against an EMPTY exclusion set, so a "
            "real CUDA/TensorRT/missing-OE-recipe hit could be reported as "
            "clean. Run tools/rollout.sh first, or pass --excluded explicitly.",
            file=sys.stderr,
        )
    else:
        excluded_path = Path(args.excluded)
        if not excluded_path.is_file():
            print(
                f"WARNING: --excluded path {excluded_path} does not exist -- "
                "closure will be checked against an EMPTY exclusion set, so a "
                "real CUDA/TensorRT/missing-OE-recipe hit could be reported "
                "as clean.",
                file=sys.stderr,
            )
        else:
            data = json.loads(excluded_path.read_text())
            for entry in data.get("skipped", []):
                excluded_by_name[entry["name"]] = entry["category"]
            print(f"(checking against exclusions from {excluded_path})", file=sys.stderr)

    visited = set()
    leaves = set()  # deps with no node in graph -- not generated by mash (meta-ros2-jazzy etc.)
    order = []

    def walk(pn):
        if pn in visited:
            return
        visited.add(pn)
        if pn not in graph:
            leaves.add(pn)
            return
        order.append(pn)
        for dep in sorted(graph[pn]):
            walk(dep)

    for seed in args.seeds:
        if seed not in graph:
            print(f"WARNING: seed '{seed}' not found in {recipes_dir} -- typo, or not synced by this rollout?", file=sys.stderr)
        walk(seed)

    hits = {pn: excluded_by_name[pn] for pn in visited if pn in excluded_by_name}

    print(f"Forward closure of {args.seeds}: {len(visited)} packages ({len(order)} mash-generated, {len(leaves)} leaves outside generated-recipes/)")
    if hits:
        print(f"\n*** HITS a known-excluded package -- {len(hits)} ***")
        for pn, cat in sorted(hits.items()):
            print(f"  {pn}: {cat}")
    else:
        print("\nNo hits against the excluded set -- closure is clean.")

    print(f"\nFull closure ({len(order)} generated packages):")
    for pn in sorted(order):
        print(f"  {pn}")

    return 1 if hits else 0


if __name__ == "__main__":
    sys.exit(main())
