#!/usr/bin/env python3
"""List every generated package that depends, directly or transitively, on the
lanelet2 family. lanelet2_core's CMake config needs mrt_cmake_modules, which no
package.xml declares, so each of these needs it added (autoware-fixups.bbclass).

Usage:
    tools/find-lanelet2-closure.py [generated-recipes-dir]

Writes meta-autoware/lanelet2-mrt-cmake-modules-chain.list. Rerun after every
tools/rollout.sh.
"""
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _recipe_graph import build_graph  # noqa: E402


def is_seed_name(name):
    return name == "autoware-lanelet2-extension" or name.startswith("lanelet2")


def main():
    recipes_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO_ROOT / "meta-autoware" / "generated-recipes"
    if not recipes_dir.is_dir():
        print(f"FAIL: {recipes_dir} not found", file=sys.stderr)
        sys.exit(1)

    graph = build_graph(recipes_dir)

    memo = {}

    def depends_on_seed(pn, stack=None):
        if is_seed_name(pn):
            return True
        if pn in memo:
            return memo[pn]
        stack = stack or set()
        if pn in stack:
            return False  # dependency cycle guard, shouldn't happen but don't hang
        stack.add(pn)
        deps = graph.get(pn, ())
        # lanelet2-* are meta-ros recipes, not graph nodes, so a direct edge counts too
        result = any(is_seed_name(dep) or depends_on_seed(dep, stack) for dep in deps)
        memo[pn] = result
        return result

    closure = sorted(pn for pn in graph if depends_on_seed(pn))

    out_path = REPO_ROOT / "meta-autoware" / "lanelet2-mrt-cmake-modules-chain.list"
    out_path.write_text(
        "# Generated by tools/find-lanelet2-closure.py, read by autoware-fixups.bbclass\n"
        + "".join(f"{pn}\n" for pn in closure)
    )
    print(f"{len(closure)} packages transitively depend on the lanelet2 family:")
    for pn in closure:
        print(f"  {pn}")
    print(f"\nWritten to {out_path}")


if __name__ == "__main__":
    main()
