#!/usr/bin/env python3
"""Write the Tier 1 packagegroups from meta-autoware/package-categories.json.

Run after tools/categorize-packages.py. Hand-written groups (core, full,
perception, simulation, devtools, planning-simulator-demo) are not touched.

Usage: tools/generate-tier1-packagegroups.py
"""
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CATEGORIES_PATH = REPO_ROOT / "meta-autoware" / "package-categories.json"
OUT_DIR = REPO_ROOT / "meta-autoware" / "recipes-core" / "packagegroups"

TIER1_CATEGORIES = (
    "msgs", "common", "sensing", "localization", "planning",
    "control", "map", "vehicle", "system",
)

DESCRIPTIONS = {
    "msgs": "Message/interface packages (near-zero deps)",
    "common": "Cross-cutting utilities and infra (autoware_utils, adapi, agnocast, ...)",
    "sensing": "Generic driver frameworks and interfaces, no vendor drivers",
    "localization": "Pose/odometry estimation (NDT, EKF, GNSS-based, ...)",
    "planning": "Rule-based planning, prediction/tracking consumers, traffic-light decision logic",
    "control": "Vehicle command generation, MRM/hazard response",
    "map": "Map loading and lanelet2",
    "vehicle": "Generic vehicle interface, description and info packages",
    "system": "Diagnostics, component/system monitoring",
}


def main():
    data = json.loads(CATEGORIES_PATH.read_text())
    by_cat = {}
    for pn, cat in data.items():
        by_cat.setdefault(cat, []).append(pn)

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for cat in TIER1_CATEGORIES:
        names = sorted(by_cat.get(cat, []))
        rdepends_lines = "".join(f"    {n} \\\n" for n in names)
        content = f"""# Generated by tools/generate-tier1-packagegroups.py, do not edit
DESCRIPTION = "Autoware {cat}: {DESCRIPTIONS[cat]}"
LICENSE = "Apache-2.0"
PACKAGE_ARCH = "${{MACHINE_ARCH}}"

inherit packagegroup

PACKAGES = "${{PN}}"
ALLOW_EMPTY:${{PN}} = "1"

RDEPENDS:${{PN}} += "\\
{rdepends_lines}"
"""
        out_path = OUT_DIR / f"packagegroup-autoware-{cat}.bb"
        out_path.write_text(content)
        print(f"wrote {out_path} ({len(names)} packages)")


if __name__ == "__main__":
    main()
