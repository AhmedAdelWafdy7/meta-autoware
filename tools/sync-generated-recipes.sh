#!/usr/bin/env bash
# Copy mash-generated recipes for every package in an allowlist from
# results/<name>/build_mash/ into meta-autoware/generated-recipes/.
#
# Usage: tools/sync-generated-recipes.sh <results-dir-name> [packages-list] [output-dir]
#   packages-list  defaults to meta-autoware/PACKAGES.list
#   output-dir     defaults to meta-autoware/generated-recipes
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

RESULTS_NAME="${1:?usage: $0 <results-dir-name> [packages-list-file] [output-dir]}"
PACKAGES_LIST="${2:-$REPO_ROOT/meta-autoware/PACKAGES.list}"
GENERATED_RECIPES_DIR="${3:-$REPO_ROOT/meta-autoware/generated-recipes}"

BUILD_MASH_DIR="$REPO_ROOT/results/$RESULTS_NAME/build_mash"

if [ ! -d "$BUILD_MASH_DIR" ]; then
  echo "error: $BUILD_MASH_DIR not found -- run tools/run-mash.sh first" >&2
  exit 1
fi
if [ ! -f "$PACKAGES_LIST" ]; then
  echo "error: $PACKAGES_LIST not found" >&2
  exit 1
fi

mkdir -p "$GENERATED_RECIPES_DIR"

SYNCED=0
MISSING=0

while IFS= read -r PKG; do
  [ -z "$PKG" ] && continue
  case "$PKG" in \#*) continue ;; esac

  SRC="$BUILD_MASH_DIR/$PKG"
  if [ ! -d "$SRC" ]; then
    echo "  skip: $PKG (not in this run's manifest/mode)" >&2
    MISSING=$((MISSING + 1))
    continue
  fi

  DST="$GENERATED_RECIPES_DIR/$PKG"
  rm -rf "$DST"
  cp -r "$SRC" "$DST"

  for BB in "$DST"/*.bb; do
    [ -f "$BB" ] || continue
    if ! grep -q "Generated by mash" "$BB"; then
      { echo "# Generated by mash -- DO NOT EDIT. Fixes go in"; \
        echo "# meta-autoware/classes/autoware-fixups.bbclass or a .bbappend."; \
        echo; \
        cat "$BB"; } > "$BB.tmp"
      mv "$BB.tmp" "$BB"
    fi
  done

  # which autoware-fixups.bbclass predicates will apply
  COVERAGE="none known -- build it, consult tools/find-missing-cmake-dep.sh on failure"
  CONTENT="$(cat "$DST"/*.bb 2>/dev/null || true)"
  HITS=""
  if grep -q "rosidl-default-runtime" <<<"$CONTENT"; then
    HITS="${HITS}rosidl-typesupport-rdepends "
  fi
  if grep -q "rosidl-default-generators" <<<"$CONTENT" && ! grep -q "rosidl-default-generators-native" <<<"$CONTENT"; then
    HITS="${HITS}buildtool-depend-tag-bug "
  fi
  if grep -qi "lanelet2" <<<"$CONTENT"; then
    HITS="${HITS}lanelet2-chain(check-tuple-membership) "
  fi
  [ -n "$HITS" ] && COVERAGE="$HITS"

  echo "  synced: $PKG  [predicate coverage: $COVERAGE]"
  SYNCED=$((SYNCED + 1))
done < "$PACKAGES_LIST"

echo
echo "Synced $SYNCED package(s), $MISSING not found in this run's build_mash/."
